BEGIN;

CREATE SCHEMA IF NOT EXISTS catalogos;

CREATE TABLE IF NOT EXISTS catalogos.libro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    autor VARCHAR(100) NOT NULL,
    anio_publicacion INTEGER NOT NULL,
    precio NUMERIC(12, 2) NOT NULL,
    CONSTRAINT chk_anio CHECK (anio_publicacion BETWEEN 1450 AND 2100),
    CONSTRAINT chk_precio CHECK (precio >= 0)
);

INSERT INTO catalogos.libro (titulo, autor, anio_publicacion, precio)
SELECT datos.titulo, datos.autor, datos.anio_publicacion, datos.precio
FROM (VALUES
    ('Cien años de soledad', 'Gabriel García Márquez', 1967, 350.00),
    ('Don Quijote de la Mancha', 'Miguel de Cervantes', 1605, 450.00)
) AS datos(titulo, autor, anio_publicacion, precio)
WHERE NOT EXISTS (
    SELECT 1 FROM catalogos.libro AS existente
    WHERE existente.titulo = datos.titulo
      AND existente.autor = datos.autor
      AND existente.anio_publicacion = datos.anio_publicacion
);

